'use strict';

const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const root = path.resolve(__dirname, '..');
const inFile = path.join(root, 'src', 'bot', 'renderer', 'src', 'styles.css');
const outFile = path.join(root, 'src', 'bot', 'renderer', 'src', 'styles.scoped.css');
const SCOPE = '.bot-root';

function scopeSelector(sel) {
  const s = sel.trim();
  if (/^(html|body|#root)$/.test(s)) return SCOPE;
  // :root, :root[data-theme='x'], :root:not([data-theme]) ...
  const m = /^:root((?:\[[^\]]*\]|:not\([^)]*\))*)(.*)$/.exec(s);
  if (m) {
    const attrs = m[1];
    const rest = m[2].trim();
    const base = attrs ? `:root${attrs} ${SCOPE}` : SCOPE;
    return rest ? `${base} ${rest}` : base;
  }
  return `${SCOPE} ${s}`;
}

function inKeyframes(node) {
  for (let p = node.parent; p; p = p.parent) if (p.type === 'atrule' && /keyframes$/i.test(p.name)) return true;
  return false;
}

function main() {
  const css = fs.readFileSync(inFile, 'utf8');
  const ast = postcss.parse(css, { from: inFile });
  let dropped = 0;
  ast.walkRules((rule) => {
    if (inKeyframes(rule)) return;
    if (/scrollbar/.test(rule.selector)) {
      rule.remove();
      dropped++;
      return;
    }
    rule.walkDecls(/^scrollbar-/, (d) => d.remove());
    if (!rule.nodes.length) return void rule.remove();
    rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
  });
  const head = `/* Generated by scripts/scope-bot-css.cjs from styles.css (AutoBotH) - do not edit; edit styles.css and run npm run scope-css */\n`;
  fs.writeFileSync(outFile, head + ast.toString(), 'utf8');
  console.log(`[scope-bot-css] ${path.relative(root, outFile)} (${dropped} scrollbar rules dropped)`);
}

main();
