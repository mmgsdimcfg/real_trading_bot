//   samples, MCP servers, backtester) is not bundled. This script makes a partial clone (--filter=blob:none, sparse checkout of only the
//   API folders HtsH uses, ~0.4 MB) into .kis-spec/ (git-ignored), reads each example's API_URL / tr_id / params / output names and the
//   COLUMN_MAPPING of its chk_*.py (field -> Korean label; for the websocket TRs the order of the realtime columns), and writes
//   src/shared/kisSpec.generated.ts. The app calls the REST endpoints itself with that spec. Re-run after KIS updates the repo:
//   npm run sync-spec   (needs git + network; the generated file is committed, so a normal build does not)
// - The Python files are read as text only - nothing from the repo is executed)

'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const REPO = 'https://github.com/koreainvestment/open-trading-api.git';
const root = path.resolve(__dirname, '..');
const work = path.join(root, '.kis-spec');
const outFile = path.join(root, 'src', 'shared', 'kisSpec.generated.ts');

/** examples_llm/domestic_stock/<api> folders used by HtsH */
const APIS = [
  'inquire_price',
  'inquire_asking_price_exp_ccn',
  'inquire_ccnl',
  'inquire_time_itemconclusion',
  'inquire_time_itemchartprice',
  'inquire_time_dailychartprice',
  'inquire_daily_itemchartprice',
  'inquire_daily_price',
  'inquire_investor',
  'investor_trade_by_stock_daily',
  'search_stock_info',
  'intstock_multprice',
  'volume_rank',
  'fluctuation',
  'market_cap',
  'inquire_index_price',
  'inquire_daily_indexchartprice',
  'news_title',
  'chk_holiday',
  'ccnl_krx',
  'asking_price_krx',
  'ccnl_total',
  'asking_price_total',
];

const git = (args, cwd = work) => execFileSync('git', args, { cwd, stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });

function checkout() {
  if (!fs.existsSync(path.join(work, '.git'))) {
    fs.mkdirSync(work, { recursive: true });
    git(['clone', '--depth', '1', '--filter=blob:none', '--no-checkout', REPO, '.']);
  } else {
    git(['fetch', '--depth', '1', 'origin', 'HEAD']);
    git(['reset', '--soft', 'FETCH_HEAD']);
  }
  git(['sparse-checkout', 'init', '--no-cone']);
  git(['sparse-checkout', 'set', '--no-cone', ...APIS.map((a) => `/examples_llm/domestic_stock/${a}/`)]);
  git(['checkout', '-f', 'HEAD']);
  return git(['rev-parse', 'HEAD']).trim();
}

function parseApi(name) {
  const dir = path.join(work, 'examples_llm', 'domestic_stock', name);
  const src = fs.readFileSync(path.join(dir, `${name}.py`), 'utf8');
  const url = (/API_URL\s*=\s*"([^"]+)"/.exec(src) || [])[1] || '';
  const trIds = [...new Set([...src.matchAll(/tr_id\s*=\s*"([^"]+)"/g)].map((m) => m[1]))];
  const pm = /params\s*=\s*\{([\s\S]*?)\n\s*\}/.exec(src);
  const params = pm ? [...pm[1].matchAll(/"([A-Za-z0-9_]+)"\s*:/g)].map((m) => m[1]) : [];
  const outputs = [...new Set([...src.matchAll(/\.(output\d?)\b/g)].map((m) => m[1]))].sort();
  // websocket TRs: realtime column order from `columns = [ ... ]`
  const cm = /columns\s*=\s*\[([\s\S]*?)\]/.exec(src);
  const wsColumns = cm ? [...cm[1].matchAll(/"([A-Za-z0-9_]+)"/g)].map((m) => m[1]) : [];
  const labels = {};
  const chk = path.join(dir, `chk_${name}.py`);
  if (fs.existsSync(chk)) {
    const c = fs.readFileSync(chk, 'utf8');
    for (const m of c.matchAll(/[A-Z_]*COLUMN_MAPPING[A-Z0-9_]*\s*=\s*\{([\s\S]*?)\n\}/g)) {
      for (const p of m[1].matchAll(/['"]([^'"]+)['"]\s*:\s*['"]([^'"]+)['"]/g)) if (!(p[1] in labels)) labels[p[1]] = p[2];
    }
  }
  const doc = ((/"""\s*\n\s*([^\n]+)/.exec(src) || [])[1] || '').trim();
  return { name, url, trIds, params, outputs, wsColumns, labels, doc };
}

function main() {
  const commit = checkout();
  const spec = {};
  for (const a of APIS) spec[a] = parseApi(a);
  const head = `// Generated by scripts/sync-kis-spec.cjs - do not edit.
// Source: ${REPO} @ ${commit}
// Files: examples_llm/domestic_stock/{${APIS.join(',')}}/*.py (read as text)
`;
  const body = `export interface KisApiSpec {
  name: string;
  /** REST path ('' for websocket TRs) */
  url: string;
  trIds: string[];
  params: string[];
  outputs: string[];
  /** websocket TRs: field order of a realtime record */
  wsColumns: string[];
  /** response field -> Korean label (chk_*.py COLUMN_MAPPING) */
  labels: Record<string, string>;
  doc: string;
}

export const KIS_SPEC_COMMIT = ${JSON.stringify(commit)};

export const KIS_SPEC: Record<string, KisApiSpec> = ${JSON.stringify(spec, null, 2)};
`;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, head + '\n' + body, 'utf8');
  const missing = APIS.filter((a) => !spec[a].url && !spec[a].wsColumns.length);
  console.log(`[sync-kis-spec] ${APIS.length} APIs @ ${commit.slice(0, 10)} -> ${path.relative(root, outFile)}${missing.length ? ` (no url/columns: ${missing.join(', ')})` : ''}`);
}

main();
