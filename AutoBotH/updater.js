/*
 * Update log
 * - [2026-10-15] type=feat - New module (shared by the make_utils Electron programs, same file in each): update check/download against the
 *   self-hosted feed https://update.iccid.dev/<productName>/ (electron-updater generic provider - static files behind the Cloudflare Tunnel).
 *   initUpdater({ productName, getMainWindow, getVersionLabel }) registers the IPC used by update-ui.js:
 *   'update-check' (manual check), 'update-download' (installer: download with 'update-progress' events; portable: open the portable exe
 *   URL in the browser, since electron-updater can only replace NSIS installs), 'update-install' (quitAndInstall).
 *   The startup check runs once a few seconds after the main window loads and only notifies the renderer ('update-available')
 *   when a newer version exists - offline/server down is silently ignored.
 *   latest.yml is generated by electron-builder; scripts/release.cjs appends buildNumber/portableFile/releaseNotes.
 *   Comparison is semver only (version), so a release must raise X.Y.Z. UPDATE_FEED overrides the feed for testing
 * - [2026-10-26] type=feat - Build number counts too: preferBuildNumber() wraps autoUpdater.isUpdateAvailable so a release with the same
 *   X.Y.Z and a higher latest.yml buildNumber than the local version.txt (e.g. 1.0.3_003 over 1.0.3_002) is offered as an update;
 *   a different X.Y.Z still follows electron-updater's semver rule. Installed copies with the previous updater.js only see X.Y.Z changes
 */
const { app, ipcMain, shell, BrowserWindow } = require('electron');
const fs = require('fs');
const path = require('path');

const STARTUP_CHECK_DELAY_MS = 5000;
const isPortable = !!process.env.PORTABLE_EXECUTABLE_DIR;

let feedUrl = '';
let versionLabel = () => `v${app.getVersion()}`;
let autoUpdater = null;
let latestInfo = null;
let downloading = null;   // Promise while a download is in progress
let downloaded = false;

function errMessage(err) {
  return (err && err.message ? err.message : String(err)).split('\n')[0];
}

function getUpdater() {
  if (autoUpdater) return autoUpdater;
  autoUpdater = require('electron-updater').autoUpdater;
  autoUpdater.setFeedURL({ provider: 'generic', url: feedUrl });
  autoUpdater.autoDownload = false;            // ask the user first
  autoUpdater.autoInstallOnAppQuit = true;     // downloaded but "later" → installed when the app quits
  autoUpdater.disableWebInstaller = true;
  autoUpdater.logger = process.env.UPDATE_DEBUG ? console : null;
  preferBuildNumber(autoUpdater, () => app.getVersion(), readLocalBuildNumber);
  return autoUpdater;
}

// electron-updater compares only the semver (1.0.3), so 1.0.3_003 would not be offered to 1.0.3_002. Like a 4-part Windows
// file version (1.0.3.3) or Android versionCode, a release with the same X.Y.Z but a higher buildNumber (latest.yml
// 'buildNumber', appended by scripts/release.cjs) also counts as newer. A different X.Y.Z keeps electron-updater's own rule
function preferBuildNumber(updater, getVersion, getBuildNumber) {
  const semverRule = updater.isUpdateAvailable.bind(updater);
  updater.isUpdateAvailable = async (info) => {
    const remoteBuild = parseInt(info && info.buildNumber, 10);
    const localBuild = getBuildNumber();
    if (info && info.version === getVersion() && remoteBuild > 0 && localBuild > 0) return remoteBuild > localBuild;
    return semverRule(info);
  };
}

// version.txt next to this file ("1.0.0_001" - packaged with the app): { label: 'v1.0.0_001', build: 1 } or null
function readVersionTxt() {
  try {
    const line = fs.readFileSync(path.join(__dirname, 'version.txt'), 'utf8')
      .split(/\r?\n/).map(s => s.trim()).find(s => s && !s.startsWith('#'));
    const m = /^v?(\d+\.\d+\.\d+)_(\d{3})$/.exec(line || '');
    if (m) return { label: `v${m[1]}_${m[2]}`, build: parseInt(m[2], 10) };
  } catch (e) {}
  return null;
}
function readLocalBuildNumber() { const v = readVersionTxt(); return v ? v.build : 0; }

// "v1.0.0_001" from version.txt (falls back to the semver of package.json)
function readVersionTxtLabel() {
  const v = readVersionTxt();
  return v ? v.label : `v${app.getVersion()}`;
}

function toPayload(info) {
  const build = info.buildNumber ? String(info.buildNumber).padStart(3, '0') : '';
  let notes = '';
  if (typeof info.releaseNotes === 'string') notes = info.releaseNotes;
  else if (Array.isArray(info.releaseNotes)) notes = info.releaseNotes.map(n => n.note || '').join('\n');
  return {
    version: info.version,
    label: `v${info.version}${build ? '_' + build : ''}`,
    current: versionLabel(),
    portable: isPortable,
    releaseNotes: notes,
    releaseDate: info.releaseDate || ''
  };
}

/* { status: 'available' | 'none' | 'error' | 'dev', info?, message? } */
async function checkForUpdate() {
  if (!app.isPackaged) return { status: 'dev' };
  try {
    const r = await getUpdater().checkForUpdates();
    if (r && r.isUpdateAvailable && r.updateInfo) {
      latestInfo = r.updateInfo;
      return { status: 'available', info: toPayload(r.updateInfo) };
    }
    return { status: 'none', current: versionLabel() };
  } catch (err) {
    return { status: 'error', message: errMessage(err) };
  }
}

function initUpdater({ productName, getMainWindow, getVersionLabel } = {}) {
  feedUrl = process.env.UPDATE_FEED || `https://update.iccid.dev/${productName}/`;
  versionLabel = getVersionLabel || readVersionTxtLabel;
  const mainWindow = () => {
    const w = getMainWindow ? getMainWindow() : BrowserWindow.getAllWindows()[0];
    return w && !w.isDestroyed() ? w : null;
  };

  ipcMain.handle('update-check', () => checkForUpdate());

  ipcMain.handle('update-download', async (event) => {
    if (!latestInfo) return { ok: false, message: 'No update information' };
    if (isPortable) {
      // Portable cannot be replaced in place - hand the new portable exe (or the release folder) to the browser
      shell.openExternal(feedUrl + (latestInfo.portableFile ? encodeURIComponent(latestInfo.portableFile) : ''));
      return { ok: true, opened: true };
    }
    if (downloaded) return { ok: true };
    const sender = event.sender;
    const onProgress = (p) => {
      if (!sender.isDestroyed()) sender.send('update-progress', { percent: p.percent || 0, transferred: p.transferred, total: p.total });
    };
    const u = getUpdater();
    u.on('download-progress', onProgress);
    try {
      if (!downloading) downloading = u.downloadUpdate();
      await downloading;
      downloaded = true;
      return { ok: true };
    } catch (err) {
      return { ok: false, message: errMessage(err) };
    } finally {
      downloading = null;
      u.removeListener('download-progress', onProgress);
    }
  });

  ipcMain.on('update-install', () => {
    if (!downloaded) return;
    // isSilent=true (no installer wizard, keeps the existing install scope/folder), isForceRunAfter=true (restart the app after install)
    setImmediate(() => getUpdater().quitAndInstall(true, true));
  });

  // Startup check - only the main window shows the dialog; nothing is shown when up to date or offline
  app.whenReady().then(() => {
    if (!app.isPackaged) return;
    const start = () => setTimeout(async () => {
      const r = await checkForUpdate();
      const w = mainWindow();
      if (r.status === 'available' && w) w.webContents.send('update-available', r.info);
    }, STARTUP_CHECK_DELAY_MS);
    // The window may be created later in the same whenReady tick - wait for it briefly
    let tries = 0;
    const wait = () => {
      const w = mainWindow();
      if (!w) { if (++tries < 50) setTimeout(wait, 200); return; }
      if (w.webContents.isLoading()) w.webContents.once('did-finish-load', start);
      else start();
    };
    wait();
  });
}

module.exports = { initUpdater, preferBuildNumber };
