function getAppVersionLabel(): string {
  try {
    const line = readFileSync(join(app.getAppPath(), 'version.txt'), 'utf8')
      .split(/\r?\n/)
      .map((s) => s.trim())
      .find((s) => s && !s.startsWith('#'));
    const m = /^v?(\d+\.\d+\.\d+_\d{3})$/.exec(line || '');
    if (m) return `v${m[1]}`;
  } catch {
    /* fall back */
  }
  return `v${app.getVersion()}`;
}

